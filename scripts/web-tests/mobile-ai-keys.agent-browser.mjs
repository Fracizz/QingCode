import { execFileSync } from 'node:child_process'
import { mkdirSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

const session = `mobile-ai-keys-${process.pid}`
const directory = resolve('.dev/web-tests/mobile-ai-keys')
mkdirSync(directory, { recursive: true })
const results = []
const run = (...args) => execFileSync('agent-browser', ['--session', session, ...args], { encoding: 'utf8', timeout: 30000 })
const evaluate = expression => run('eval', expression)
const check = (name, expression) => { run('wait', '--fn', expression); results.push({ name, passed: true }) }
const capture = name => run('screenshot', resolve(directory, `${name}.png`))
const press = key => run('click', `#special-keys [data-key="${key}"]`)
const more = key => {
  run('wait', '--fn', `!document.querySelector('#more-keys').disabled`)
  run('click', '#more-keys')
  run('wait', '--fn', `document.querySelector('#keys-dialog').open && document.querySelector('#keys-dialog').getAnimations().every(a => a.playState === 'finished')`)
  run('click', `#keys-dialog [data-key="${key}"]`)
}
const inputs = `window.__mobileFixture.state.inputs.join('')`
const draft = `document.querySelector('#compose').value`
const mode = `document.querySelector('#input-mode').textContent`
const reset = () => evaluate('window.__mobileFixture.state.inputs.length = 0')
const hold = () => evaluate(`document.querySelector('[data-key="backspace"]').dispatchEvent(new PointerEvent('pointerdown', {pointerType:'touch'}))`)
const release = () => evaluate(`document.querySelector('[data-key="backspace"]').dispatchEvent(new PointerEvent('pointerup', {pointerType:'touch'}))`)

try {
  run('set', 'viewport', '390', '844')
  run('open', 'http://127.0.0.1:38439/mobile-android/')
  evaluate('localStorage.clear(); location.reload()')
  check('真实 Android 资产已就绪', `typeof window.qingLink === 'function'`)
  evaluate(`window.Terminal = class extends window.Terminal { constructor(...args) {super(...args); window.__keysTerm = this} }; window.qingLink(window.__mobileFixture.link('192.168.1.8',48764))`)
  run('fill', '#pair-code', 'A8z2D3')
  run('click', '#pair-submit')
  check('电脑连接成功', `document.querySelector('#active-host').dataset.state === 'online'`)
  run('click', '#dashboard-nav [data-page="project"]')
  run('click', '#project-list .row:first-child')
  check('终端可输入', `document.querySelector('#terminal-status').textContent === '会话中'`)
  evaluate(`window.__keyEvents = []; document.addEventListener('click', e => window.__keyEvents.push({id:e.target.id,key:e.target.dataset.key,disabled:e.target.disabled}),true)`)
  check('常用区为单行，Esc、Tab、Ctrl+C 在最前，没有重复补全工具栏', `(() => { const keys = [...document.querySelector('#special-keys').children]; return keys.length === 11 && keys.slice(0, 3).map(k => k.dataset.key).join() === 'esc,tab,interrupt' && new Set(keys.map(k => Math.round(k.getBoundingClientRect().top))).size === 1 && !document.querySelector('#completion-tools'); })()`)

  reset()
  run('fill', '#compose', '前👨‍👩‍👧‍👦后')
  evaluate(`document.querySelector('#compose').setSelectionRange(12,12); document.activeElement.blur()`)
  press('backspace')
  check('失焦后退格仍完整删除本地 emoji，不发远端输入', `${draft} === '前后' && ${inputs} === '' && ${mode} === '手机草稿'`)
  evaluate(`document.querySelector('#compose').setSelectionRange(0,1)`)
  press('backspace')
  check('本地退格优先删除选中文字', `${draft} === '后' && ${inputs} === ''`)
  run('fill', '#compose', 'hello world')
  more('delete-word')
  check('删词只删除本地前一个词', `${draft} === 'hello ' && ${inputs} === ''`)
  more('clear')
  check('清空草稿只清空手机文本', `${draft} === '' && ${inputs} === ''`)
  run('fill', '#compose', '前后')
  evaluate(`document.querySelector('#compose').setSelectionRange(1,1)`)
  more('newline')
  check('换行插入本地光标处，不提交内容', `${draft} === ${JSON.stringify('前\n后')} && ${inputs} === ''`)

  run('fill', '#compose', '')
  press('slash')
  run('keyboard', 'type', 'eff')
  check('斜杠前缀直接进入终端并切换输入标识', `${inputs} === '/eff' && ${mode} === '终端实时输入' && document.querySelector('#send-label').textContent === '确认'`)
  evaluate('document.activeElement.blur()')
  press('backspace')
  check('收起键盘后退格发送 DEL，不丢失远端输入位置', `${inputs} === '/eff' + String.fromCharCode(127) && ${mode} === '终端实时输入'`)
  run('click', '#more-keys')
  run('wait', '300')
  check('远端编辑时禁止清空手机草稿', `document.querySelector('#keys-target').textContent.includes('终端实时输入') && document.querySelector('#keys-dialog [data-key="clear"]').disabled`)
  run('click', '#keys-dialog [data-key="delete-line-start"]')
  check('删至行首发送 Ctrl+U，不发送 Ctrl+C', `${inputs}.endsWith(String.fromCharCode(21)) && !${inputs}.includes(String.fromCharCode(3))`)
  reset()
  more('reference')
  press('tab')
  press('shift-tab')
  press('esc')
  more('newline')
  check('@、Tab、Shift+Tab、Esc、换行分别发送原生按键，无隐含回车', `${inputs} === ${JSON.stringify('@\t\x1b[Z\x1b\n')}`)
  run('click', '#send')
  check('只有明确确认才发送一次回车', `${inputs} === ${JSON.stringify('@\t\x1b[Z\x1b\n\r')}`)

  run('click', '#keyboard')
  run('fill', '#compose', '保留的手机草稿')
  run('click', '#keyboard')
  reset()
  press('backspace')
  run('click', '#send')
  check('实时编辑和确认不会发送或清空保留的手机草稿', `${draft} === '保留的手机草稿' && ${inputs} === ${JSON.stringify('\x7f\r')}`)
  run('click', '#keyboard')
  evaluate(`document.querySelector('#compose').setSelectionRange(0,0)`)
  press('right')
  check('切回草稿后箭头编辑本地光标', `document.querySelector('#compose').selectionStart === 1 && ${inputs} === ${JSON.stringify('\x7f\r')}`)
  evaluate(`document.querySelector('#compose').dispatchEvent(new CompositionEvent('compositionstart')); document.querySelector('[data-key="backspace"]').click(); document.querySelector('#compose-form').requestSubmit()`)
  check('中文组词期间不删除或提交', `${draft} === '保留的手机草稿' && ${inputs} === ${JSON.stringify('\x7f\r')} && document.querySelector('[data-key="backspace"]').disabled`)
  evaluate(`document.querySelector('#compose').dispatchEvent(new CompositionEvent('compositionend'))`)
  run('fill', '#compose', '')
  press('slash')
  check('退格连发前斜杠已发到远端', `${inputs}.endsWith('/')`)
  reset()
  hold()
  check('长按退格连续发送字符删除', `${inputs}.length >= 2`)
  release()
  evaluate(`window.__repeatCount = window.__mobileFixture.state.inputs.join('').length; window.__releasedAt = performance.now()`)
  check('松手后停止连发', `performance.now() - window.__releasedAt > 250 && ${inputs}.length === window.__repeatCount`)
  check('连续退格不会转换为清空或退出快捷键', `Array.from(${inputs}).every(c => c.charCodeAt(0) === 127)`)
  reset()
  hold()
  run('click', '#new-session')
  run('click', '#new-session-dialog [data-launch="shell"]')
  check('新会话使用独立的手机草稿输入位置', `document.querySelectorAll('#session-options .session-option').length === 2 && ${mode} === '手机草稿'`)
  evaluate(`window.__switchedCount = window.__mobileFixture.state.inputs.join('').length; window.__switchedAt = performance.now()`)
  check('切换会话取消旧会话的长按计时器', `performance.now() - window.__switchedAt > 600 && ${inputs}.length === window.__switchedCount`)
  run('click', '#show-sessions')
  run('click', '#session-options .session-option:first-child .row')
  check('切回会话恢复远端实时输入位置', `${mode} === '终端实时输入' && document.querySelector('#terminal-status').textContent === '会话中' && !document.querySelector('#more-keys').disabled`)
  run('click', '#keyboard')
  run('fill', '#compose', '')
  reset()
  more('alt')
  evaluate(`document.querySelector('#keys-dialog').close()`)
  run('click', '#special-keys [data-key="interrupt"]')
  check('常用区 Ctrl+C 不受 Alt 修饰影响', `${inputs} === String.fromCharCode(3) && document.querySelector('#keys-dialog [data-key="alt"]').getAttribute('aria-pressed') === 'false'`)
  run('click', '#keyboard')
  for (const [name, width, height] of [['phone',390,844],['narrow',320,740],['keyboard',390,430],['landscape',844,390]]) {
    run('set', 'viewport', String(width), String(height))
    evaluate(`if(document.querySelector('#special-keys').hidden) document.querySelector('#toggle-keys').click(); document.querySelector('#special-keys').scrollLeft = 0`)
    check(`${name}：按键触摸区至少 44px 且输入栏不溢出`, `document.documentElement.scrollWidth <= innerWidth && [...document.querySelectorAll('#special-keys button')].every(b => b.getBoundingClientRect().width >= 44 && b.getBoundingClientRect().height >= 44) && document.querySelector('#compose-form').getBoundingClientRect().bottom <= innerHeight`)
    capture(name)
  }
  const errors = JSON.parse(run('errors', '--json'))
  if (errors.data?.errors?.length) throw new Error(JSON.stringify(errors.data.errors))
} catch (error) {
  try { console.error(evaluate(`({value:document.querySelector('#compose').value, mode:document.querySelector('#input-mode').textContent, selection:[document.querySelector('#compose').selectionStart,document.querySelector('#compose').selectionEnd], inputs:window.__mobileFixture.state.inputs, dialogOpen:document.querySelector('#keys-dialog').open,events:window.__keyEvents})`)); console.error(run('errors')) } catch { /* Preserve the failure. */ }
  results.push({ name: String(error), passed: false })
  try { capture('failure') } catch { /* Preserve the failure. */ }
  process.exitCode = 1
} finally {
  writeFileSync(resolve(directory, 'results.json'), JSON.stringify({ engine: 'agent-browser', nativeIntegration: false, results }, null, 2))
  const escape = text => text.replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('>','&gt;')
  writeFileSync(resolve(directory, 'report.html'), `<!doctype html><html lang="zh-CN"><meta charset="utf-8"><title>AI 编程按键验收</title><h1>AI 编程按键验收</h1><p>真实 Android 页面和 xterm，内存 RPC；不包含真实 Claude / OpenCode、PTY 或手机输入法验收。</p><ul>${results.map(r => `<li>${r.passed ? '通过' : '失败'}：${escape(r.name)}</li>`).join('')}</ul></html>`)
  try { run('close') } catch { /* Browser may already be closed. */ }
}
console.log(`${results.filter(r => r.passed).length}/${results.length} browser checks passed. ${directory}`)
