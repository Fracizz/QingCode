import { execFileSync } from 'node:child_process'
import { mkdirSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

const session = `mobile-files-${process.pid}`
const directory = resolve('.dev/web-tests/mobile-files')
mkdirSync(directory, { recursive: true })
const results = []
const run = (...args) => execFileSync('agent-browser', ['--session', session, ...args], { encoding: 'utf8', timeout: 30000 })
const evaluate = expression => run('eval', expression)
const check = (name, expression) => { run('wait', '--fn', expression); results.push({ name, passed: true }) }
const capture = name => { run('wait', '250'); return run('screenshot', resolve(directory, `${name}.png`)) }
const openEntry = path => run('click', `#files-list [data-path="${path}"]`)
const loaded = `document.querySelector('#files-list').getAttribute('aria-busy')==='false'`
const listed = path => `!!document.querySelector('#files-list [data-path=${JSON.stringify(path)}]')`
const closeDetail = () => run('click', '#file-detail-dialog [data-close]')
const fits = `document.documentElement.scrollWidth<=innerWidth && [...document.querySelectorAll('dialog[open]')].every(el=>{const r=el.getBoundingClientRect();return r.left>=0 && r.right<=innerWidth+1 && r.top>=0 && r.bottom<=innerHeight+1})`
const openProjects = () => {
  run('click', '#dashboard-nav [data-page="project"]')
  run('wait', '--fn', '!document.getElementById("project-screen").hidden && !document.documentElement.dataset.screenExit')
}
try {
  run('set', 'viewport', '390', '844')
  run('open', process.env.QINGCODE_WEB_TEST_URL || 'http://127.0.0.1:38439/mobile-android/')
  evaluate('localStorage.clear(); location.reload()')
  check('real Android assets initialize', `typeof window.qingLink==='function' && typeof window.qingFileDownload==='function'`)
  evaluate(`window.qingLink(window.__mobileFixture.link('192.168.1.8',48764))`)
  run('fill', '#pair-code', 'A8z2D3')
  run('click', '#pair-submit')
  check('computer is paired', `document.querySelector('#active-host').dataset.state==='online'`)
  openProjects()
  run('click', '#project-list .project-files')
  check('file browsing needs no terminal', `document.querySelector('#files-dialog').open && ${loaded} && ${listed('src')} && window.__mobileFixture.state.creates.length===0`)
  check('root shows its breadcrumb and sort control without a parent button', `document.querySelector('#files-breadcrumbs [aria-current="location"]').textContent==='QingCode' && getComputedStyle(document.getElementById('files-up')).display==='none' && document.getElementById('files-sort').textContent.includes('时间')`)
  capture('01-project-root')
  openEntry('src')
  check('directory supports Chinese file names', `${loaded} && ${listed('src/中文说明.txt')}`)
  check('subdirectories show the parent button', `document.getElementById('files-up').getBoundingClientRect().width>=44 && document.getElementById('files-up').getAttribute('aria-label')==='返回上级目录'`)
  capture('01-directory-controls')
  run('click', '#files-sort')
  check('time sort remains clickable', `document.getElementById('files-sort').dataset.order==='asc'`)
  run('click', '#files-sort')
  check('time sort can restore newest first', `document.getElementById('files-sort').dataset.order==='desc'`)
  run('fill', '#files-query', 'README')
  check('default query searches the whole project', `${loaded} && ${listed('README.md')}`)
  // Custom select menus preserve the real select as the value source.
  evaluate(`document.querySelector('#files-scope').value='directory';document.querySelector('#files-scope').dispatchEvent(new Event('change'))`)
  check('directory query excludes parent results', `${loaded} && document.querySelector('#files-status').textContent.includes('没有匹配')`)
  run('fill', '#files-query', '中文')
  check('Unicode query finds relative paths', `${loaded} && ${listed('src/中文说明.txt')}`)
  capture('02-file-query')
  run('click', '#files-list .file-locate')
  check('locating a result restores its directory', `${loaded} && document.querySelector('#files-query').value==='' && ${listed('src/app.ts')}`)
  run('click', '#files-up')
  check('parent navigation returns to root', `${loaded} && ${listed('README.md')}`)
  run('click', '#files-hidden')
  check('hidden files use the same list toggle', `${loaded} && ${listed('.env.example')}`)
  run('fill', '#files-query', '.env')
  check('hidden files also appear in queries', `${loaded} && ${listed('.env.example')}`)
  evaluate(`window.__mobileFixture.state.fileTruncated=true`)
  run('click', '#files-refresh')
  check('incomplete query results have an explicit warning', `${loaded} && !document.querySelector('#files-truncated').hidden`)
  evaluate(`window.__mobileFixture.state.fileTruncated=false;window.__mobileFixture.state.fileDelay=600`)
  run('fill', '#files-query', 'release')
  run('wait', '350')
  run('fill', '#files-query', 'README')
  check('late query cannot replace the newest results', `${loaded} && ${listed('README.md')} && !${listed('release.zip')}`)
  evaluate(`window.__mobileFixture.state.fileDelay=0`)
  openEntry('README.md')
  check('file details load before download', `document.querySelector('#file-detail-dialog').open && !document.querySelector('#file-download').disabled && document.querySelector('#file-detail-size').textContent.includes('KiB')`)
  check('file details show the default download directory', `document.getElementById('file-download-location').textContent==='Download/QingCode'`)
  run('click', '#file-download')
  check('small file reports download completion', `document.querySelector('#files-transfer-status').textContent==='下载完成' && window.__mobileFixture.state.fileDownloads.length===1`)
  capture('03-download-complete')
  run('click', '#files-clear')
  check('clear query restores the list', `${loaded} && ${listed('release.zip')}`)
  openEntry('release.zip')
  check('large file metadata is ready', `!document.querySelector('#file-download').disabled`)
  run('click', '#file-download')
  check('large file requires confirmation', `document.querySelector('#confirm-dialog').open && document.querySelector('#confirm-dialog').textContent.includes('256 MiB') && window.__mobileFixture.state.fileDownloads.length===1`)
  capture('04-large-file-warning')
  run('click', '#confirm-dialog button[value="cancel"]')
  check('canceling warning starts no download', `!document.querySelector('#confirm-dialog').open && window.__mobileFixture.state.fileDownloads.length===1`)
  evaluate(`window.__mobileFixture.state.fileDownloadDelay=500`)
  run('click', '#file-download')
  run('click', '#confirm-action')
  check('confirmed download shows progress', `!document.querySelector('#files-progress').hidden && window.__mobileFixture.state.fileDownloads.length===2`)
  run('click', '#files-download-cancel')
  check('in-flight download can be canceled', `document.querySelector('#files-transfer-status').textContent.includes('已取消') && !window.__mobileFixture.state.fileDownload`)
  openEntry('README.md')
  check('download button recovers after cancellation', `!document.querySelector('#file-download').disabled`)
  evaluate(`window.__mobileFixture.state.fileDownloadDelay=30;window.__mobileFixture.state.fileDownloadError='模拟网络中断'`)
  run('click', '#file-download')
  check('failure remains visible and does not retry', `document.querySelector('#files-transfer-status').textContent.includes('模拟网络中断') && window.__mobileFixture.state.fileDownloads.length===3`)
  run('wait', '500')
  check('failed transfer is never automatically restarted', `window.__mobileFixture.state.fileDownloads.length===3`)
  evaluate(`window.__mobileFixture.state.fileDownloadError=null;
    window.__mobileFixture.state.files.push({ name:'QingCode.apk',path:'QingCode.apk',isDir:false,size:1024,modifiedAt:1794600000000 })`)
  run('click', '#files-refresh')
  check('APK appears in the file list', `${loaded} && ${listed('QingCode.apk')}`)
  openEntry('QingCode.apk')
  check('APK details retain the original suffix', `!document.getElementById('file-download').disabled && document.getElementById('file-detail-name').textContent==='QingCode.apk'`)
  evaluate(`window.__mobileFixture.state.fileDownloadVisible=false`)
  run('click', '#file-download')
  evaluate(`window.qingVisibility(false)`)
  check('fixture finishes the APK while the app is in the background', `window.__mobileFixture.state.fileDownloadStatus.state==='done' && document.getElementById('files-transfer-status').textContent==='正在准备下载…'`)
  evaluate(`window.__mobileFixture.state.fileDownloadVisible=true;window.qingVisibility(true)`)
  check('returning to the app restores completion and the actual APK save location', `document.getElementById('files-transfer-status').textContent==='下载完成' && document.getElementById('files-transfer-location').textContent==='保存位置：Download/QingCode/QingCode.apk'`)
  openEntry('QingCode.apk')
  check('APK is ready for another download', `!document.getElementById('file-download').disabled`)
  run('click', '#file-download')
  check('duplicate APK downloads keep their extension and show their actual name', `document.getElementById('files-transfer-status').textContent==='下载完成' && document.getElementById('files-transfer-location').textContent==='保存位置：Download/QingCode/QingCode (1).apk'`)
  capture('04-apk-saved')
  run('set', 'viewport', '320', '640')
  check('file page fits narrow phones', fits)
  capture('05-narrow-file-page')
  run('set', 'viewport', '844', '390')
  check('file page fits landscape', fits)
  capture('06-landscape-file-page')
  run('set', 'viewport', '390', '844')
  run('click', '#files-dialog [data-close="files-dialog"]')
  run('click', '#project-list .row')
  evaluate('window.__mobileFixture.startTerminalIfEmpty()')
  check('terminal is attached', `document.querySelector('#terminal-status').textContent==='会话中'`)
  run('fill', '#compose', '保留文件浏览之前的草稿')
  evaluate(`window.__filesTerminal=window.__mobileFixture.terminal();true`)
  run('click', '#terminal-menu')
  run('wait', '300')
  run('click', '#menu-files')
  check('terminal menu opens the project files', `document.querySelector('#files-dialog').open && ${loaded}`)
  run('click', '#files-dialog [data-close="files-dialog"]')
  check('return retains the same terminal and exact draft', `document.querySelector('#compose').value==='保留文件浏览之前的草稿' && window.__mobileFixture.terminal()===window.__filesTerminal && window.__mobileFixture.state.creates.length===1`)
  capture('07-terminal-draft-retained')
  evaluate(`window.__mobileFixture.state.capabilities.features=window.__mobileFixture.state.capabilities.features.filter(x=>x!=='project_files');window.qingLink(window.__mobileFixture.link('10.0.0.9',48764,'f'.repeat(64),'旧版电脑'))`)
  check('a second computer can pair for capability compatibility', `document.querySelector('#pair-dialog').open`)
  run('fill', '#pair-code', 'A8z2D3')
  run('click', '#pair-submit')
  check('older computer is connected', `!document.querySelector('#pair-dialog').open && window.__mobileFixture.state.profiles.size===2 && document.querySelector('#active-host').dataset.state==='online'`)
  openProjects()
  run('click', '#project-list .project-files')
  check('older computers display an update explanation', `document.querySelector('#files-dialog').open && document.querySelector('#files-status').textContent.includes('更新电脑端')`)
  capture('08-older-computer')
} catch (error) {
  results.push({ passed: false, error: String(error) })
  try { capture('failure') } catch { /* Retain the original error. */ }
  process.exitCode = 1
} finally {
  writeFileSync(resolve(directory, 'results.json'), JSON.stringify({ fixtureOnly: true, results }, null, 2))
  try { run('close') } catch { /* Preserve the original failure. */ }
  console.log(JSON.stringify({ results, directory }, null, 2))
}
