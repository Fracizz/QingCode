import { execFileSync } from 'node:child_process'
import { writeFileSync, mkdirSync } from 'node:fs'
import { resolve } from 'node:path'
// Requires pnpm dev:web-test (38419), pnpm test:web (38439), and a local display.
// Both servers use isolated in-memory data; no real file, Git, SSH, or PTY operations.
const dir = resolve('.dev/web-tests/ui-interactions')
mkdirSync(dir, { recursive: true })
const session = `qingcode-ui-interactions-${process.pid}`
const browser = process.env.AGENT_BROWSER_BIN || 'agent-browser'
const run = (...args) => execFileSync(browser, ['--session', session, ...args], { encoding: 'utf8', timeout: 30000 })
const click = (name, role='button') => run('find', 'role', role, 'click', '--name', name, '--exact')
const results = []
const check = (name, js) => { run('wait','--fn',`Boolean(${js})`); results.push({ name, passed:true }) }
const shot = name => { run('wait','350'); run('screenshot',`${dir}/${name}.png`) }
try {
  execFileSync(browser, ['--session', session, '--headed', '--args', '--disable-blink-features=AutomationControlled,--test-type,--disable-web-security,--disable-features=IsolateOrigins,site-per-process,--start-maximized', 'open', `http://127.0.0.1:38419/?testSession=ui-interactions-${process.pid}`], { encoding: 'utf8', timeout: 30000 })
  run('wait', '--fn', 'Boolean(window.__QINGCODE_TEST__ && document.querySelector("button[aria-label=设置]"))')
  click('打开项目'); click('信任并继续'); click('设置')
  run('wait', '--fn', 'Boolean(document.querySelector(".settings-shell"))')
  run('set','viewport','1050','836')
  run('find','placeholder','搜索设置','fill','editor.minimap.enabled')
  check('配置键搜索显示目录和对应小地图设置', `document.querySelector('[aria-label="编辑器: 小地图"]') && document.querySelector('.settings-nav').textContent.includes('编辑器与文件')`)
  run('find','placeholder','搜索设置','fill','no-setting-matches')
  check('搜索无结果显示说明', `document.querySelector('.settings-body [role="status"]')?.textContent.includes('没有匹配')`)
  shot('settings-empty')
  run('click','.settings-body [role="status"] button')
  check('清除搜索后回到输入框', `document.activeElement?.getAttribute('placeholder') === '搜索设置'`)
  click('当前项目','tab')
  check('当前项目只显示可配置分类', `![...document.querySelectorAll('.settings-nav button')].some(e=>['外观与语言','项目与会话','工具与集成','快捷键','移动连接','更新与关于'].includes(e.textContent))`)
  click('选择面板布局'); click('编辑器+双终端','menuitemcheckbox')
  check('分屏设置列无横向溢出', `[...document.querySelectorAll('.settings-shell *')].every(e=>e.clientWidth===0 || e.scrollWidth <= e.clientWidth+2)`)
  shot('settings-split')
  click('管理设置')
  check('管理设置包含导入导出与恢复默认', `document.querySelector('[role="menu"]')?.textContent.includes('导入配置 JSON') && document.querySelector('[role="menu"]')?.textContent.includes('恢复默认设置')`)
  run('press','Escape')
  check('管理菜单关闭后恢复焦点', `document.activeElement?.getAttribute('aria-label')==='管理设置'`)
  click('多项目工作区'); run('press','End')
  check('工作区 End 定位最后操作', `document.activeElement?.textContent==='管理多项目工作区'`)
  run('press','Home')
  check('工作区 Home 定位第一个操作', `document.activeElement?.textContent==='将顶栏项目保存为工作区'`)
  run('press','Escape')
  check('工作区菜单关闭后恢复触发按钮焦点', `document.activeElement?.getAttribute('aria-label')==='多项目工作区'`)
  click('选择面板布局'); click('经典布局（终端在底部）','menuitemcheckbox')
  click('资源管理器')
  run('find','text','README.md','click','--exact')
  run('wait','--fn',`Boolean([...document.querySelectorAll('button')].find(e=>e.textContent==='编辑'))`)
  click('编辑')
  run('click','.cm-content'); run('press','Control+End'); run('keyboard','type',' UI audit preserved')
  run('eval',`window.__QINGCODE_TEST__.failNext('write_file','UI audit disk failure'); true`)
  run('find','role','tab','hover','--name','README.md 未保存的更改','--exact'); click('关闭文件')
  check('关闭文件同时提供保存放弃取消', `document.querySelector('[role="alertdialog"]')?.textContent.includes('保存并关闭') && document.querySelector('[role="alertdialog"]')?.textContent.includes('放弃更改')`)
  shot('save-before-close')
  click('保存并关闭')
  check('保存失败后保留文件和输入', `document.querySelector('.cm-content')?.textContent.includes('UI audit preserved') && document.body.textContent.includes('UI audit disk failure')`)
  shot('save-failed-retains-buffer')
  run('find','role','tab','hover','--name','README.md 未保存的更改','--exact'); click('关闭文件'); click('保存并关闭')
  check('保存成功后关闭文件并保留写入内容', `!document.querySelector('.cm-content') && window.__QINGCODE_TEST__.readFile('/workspace/demo/README.md').includes('UI audit preserved')`)
  run('eval', `document.querySelectorAll('button[aria-label="关闭通知"]').forEach(button=>button.click()); true`)
  click('运行配置')
  run('wait','--fn',`Boolean(document.querySelector('[aria-label="新建运行配置"]'))`)
  click('新建运行配置')
  run('find','label','名称','fill','UI protected draft')
  click('添加任务'); run('find','label','命令','fill','pnpm dev')
  run('press','Escape'); click('继续编辑')
  check('取消离开运行配置保留名称与命令', `document.querySelector('[aria-label="名称"]')?.value==='UI protected draft' && document.querySelector('textarea[aria-label="命令"]')?.value==='pnpm dev'`)
  click('模板'); click('保留当前内容')
  check('取消模板替换保留已有内容', `document.querySelector('[aria-label="名称"]')?.value==='UI protected draft'`)
  shot('run-draft-retained')
  click('保存')
  check('运行配置保存成功', `window.__QINGCODE_TEST__.readFile('/workspace/demo/.qingcode/run.json').includes('UI protected draft')`)
  run('open','http://127.0.0.1:38439/web-tests/remote-connections.html')
  run('wait','--fn',`Boolean([...document.querySelectorAll('button')].find(e=>e.textContent==='编辑连接'))`)
  click('编辑连接'); run('find','label','连接名称','fill','WSL draft retained')
  click('WinDev administrator@192.0.2.107:28822 检查失败 · 3 个项目')
  click('继续编辑')
  check('取消切换远程连接后保留修改', `[...document.querySelectorAll('input')].some(e=>e.value==='WSL draft retained')`)
  click('新建连接'); click('继续编辑')
  check('取消新建连接后保留修改', `[...document.querySelectorAll('input')].some(e=>e.value==='WSL draft retained')`)
  click('关闭'); click('继续编辑')
  check('取消关闭远程管理后保留表单', `[...document.querySelectorAll('input')].some(e=>e.value==='WSL draft retained')`)
  shot('remote-draft-retained')
  click('返回概览'); click('放弃修改')
  click('更多连接操作')
  check('维护操作位于更多菜单', `document.querySelector('[role="menu"]')?.textContent.includes('断开连接') && document.querySelector('[role="menu"]')?.textContent.includes('删除连接')`)
  run('press','Escape')
  check('关闭连接菜单保留管理弹窗并返回触发按钮', `document.querySelector('[role="dialog"]') && !document.querySelector('[role="menu"]') && document.activeElement?.getAttribute('aria-label')==='更多连接操作'`)
  shot('remote-overview')
  run('open','http://127.0.0.1:38439/')
  run('set','viewport','800','900')
  run('wait','--fn',`Boolean(document.querySelector('.project-manager-table'))`)
  check('800px 项目表格无横向滚动', `document.querySelector('.project-manager-table').scrollWidth<=document.querySelector('.project-manager-table').clientWidth+1`)
  check('800px 项目行操作全部可见', `[...document.querySelectorAll('.project-overflow-action')].filter(e=>e.getBoundingClientRect().width>0).length===10`)
  check('来源与项目名分行且名称可读', `getComputedStyle(document.querySelector('.project-name-label')).flexDirection==='column' && document.querySelector('.project-name-cell button').getBoundingClientRect().width>200`)
  click('项目操作：django [WSL · Ubuntu]'); run('press','Escape')
  check('项目操作菜单 Escape 保留项目管理并返回焦点', `document.querySelector('[role="dialog"]') && document.activeElement?.getAttribute('aria-label')==='项目操作：django [WSL · Ubuntu]'`)
  shot('project-manager-dark-800')
  click('关闭'); run('select','[aria-label="测试主题"]','light'); click('打开项目管理')
  shot('project-manager-light-800')
  click('关闭'); run('select','[aria-label="测试主题"]','olive'); click('打开项目管理')
  shot('project-manager-olive-800')
  click('关闭'); run('select','[aria-label="测试语言"]','en'); click('打开项目管理')
  check('英文窄窗中项目操作已翻译', `[...document.querySelectorAll('.project-overflow-action')].every(e=>e.getAttribute('aria-label').startsWith('Project actions:'))`)
  shot('project-manager-en-800')
} catch(error) {
  results.push({name:String(error),passed:false})
  try { shot('failure'); writeFileSync(`${dir}/failure-snapshot.txt`,run('snapshot','-i')) } catch {}
  process.exitCode=1
} finally {
  writeFileSync(`${dir}/results.json`,JSON.stringify({engine:'agent-browser',nativeIntegration:false,results},null,2))
  try { writeFileSync(`${dir}/browser-errors.json`,run('errors','--json')) } catch { /* Startup may have failed. */ }
  try { run('close') } catch { /* Only close this script's session. */ }
  writeFileSync(`${dir}/report.html`, `<!doctype html><meta charset="UTF-8"><title>QingCode UI interaction acceptance</title><h1>QingCode UI 与交互验收</h1><p>Linux agent-browser · 本地内存场景，未验证原生文件、SSH、Git 和 PTY。</p><pre>${JSON.stringify(results,null,2).replaceAll('&','&amp;').replaceAll('<','&lt;')}</pre>`)
  console.log(`${results.filter(r=>r.passed).length}/${results.length} UI checks passed. ${dir}`)
}
